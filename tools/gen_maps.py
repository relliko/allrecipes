"""
Generates allrecipes' zone map table from a dump of the game's FFXiMain.dll:

    data/maps.lua  each zone's maps (its floors): which picture, its scale and offsets

    python tools/gen_maps.py [--dump C:\\Games\\PhoenixXI\\FFXiMain_04490000.bin]

The game's map table (facelift's core/zonemap.lua, client-notes 'Map window'): 14-byte records
{ s16 zone, s8 floor, u8 main, u8 kinds, s8 scale, s8 key item, u8, u16 picture, s16 offset x,
s16 offset y }, ended by one whose scale is 0. The dump is a flat image loaded at 0x04490000; the
table is at 0x048121F0 (found from FindMap, 0x1F7430). A world point (x, z: Ashita's X and Y) is
at picture pixel (int(x * s / 5 + 0.5) - offset x, -int(z * s / 5 + 0.5) - offset y), s = |scale|;
the picture is DAT file 0x14C0 + picture (kinds & 0xF = 0), 0xD02F + (1) or 0xD417 + (2).
"""

import argparse
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data"

BASE = 0x04490000
TABLE = 0x048121F0
REC, MAX = 14, 1200


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", default=r"C:\Games\PhoenixXI\FFXiMain_04490000.bin")
    args = ap.parse_args()
    image = Path(args.dump).read_bytes()
    rows = []
    for i in range(MAX):
        o = TABLE - BASE + i * REC
        zone, floor, main, kinds, scale, key, _, pic, ox, oy = struct.unpack_from("<hbBBbbBHhh", image, o)
        if scale == 0:
            break
        rows.append((zone, floor, main, kinds, scale, key, pic, ox, oy))
    else:
        sys.exit("no end to the map table: wrong dump or address")
    # (Records with a negative zone are the game's own special maps; only zones are kept.)
    rows = [r for r in rows if r[0] >= 0]
    if len(rows) < 300 or not all(r[0] < 300 for r in rows) or rows[0][0] != 100:
        sys.exit("the map table doesn't look right: wrong dump or address")
    out = [
        "-- Generated by tools/gen_maps.py from the game's map table. Don't edit by hand.",
        "-- [zone] = { { floor, kinds, scale, key item (< 0 no map), picture, offset x, offset y }, ... }",
        "return {",
    ]
    by = {}
    for zone, floor, main, kinds, scale, key, pic, ox, oy in rows:
        by.setdefault(zone, []).append((floor, kinds, scale, key, pic, ox, oy))
    for zone in sorted(by):
        out.append("    [%d] = { %s }," % (zone, ", ".join("{ %d, %d, %d, %d, %d, %d, %d }" % r for r in by[zone])))
    out.append("}")
    (DATA / "maps.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("data/maps.lua: %d maps for %d zones" % (len(rows), len(by)))


if __name__ == "__main__":
    main()
